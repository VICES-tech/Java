-- Les membres du groupe et leur compte de connexion
create table membre (
    id                        bigint generated by default as identity primary key,
    nom                       varchar(255) not null,
    role                      varchar(255),
    couleur                   varchar(255),
    email                     varchar(255),
    mot_de_passe              varchar(255),
    admin                     boolean      not null default false,
    doit_changer_mot_de_passe boolean      not null default false,
    constraint uk_membre_nom   unique (nom),
    constraint uk_membre_email unique (email)
);

-- Le répertoire de chants
create table chant (
    id       bigint generated by default as identity primary key,
    titre    varchar(255) not null,
    artiste  varchar(255),
    tonalite varchar(255),
    tempo    integer,
    contenu  varchar(50000)
);

-- Les fichiers joints aux chants (le contenu est sur le disque, pas dans la base)
create table piece_jointe (
    id         bigint generated by default as identity primary key,
    chant_id   bigint       not null,
    nom        varchar(255) not null,
    type       varchar(255),
    taille     bigint       not null,
    ajoute_le  timestamp(6),
    nom_stocke varchar(255) not null,
    constraint uk_piece_jointe_nom_stocke unique (nom_stocke),
    constraint fk_piece_jointe_chant foreign key (chant_id) references chant (id)
);
create index ix_piece_jointe_chant on piece_jointe (chant_id);

-- Les événements du planning
create table evenement (
    id          bigint generated by default as identity primary key,
    titre       varchar(255)  not null,
    type        varchar(255)  not null,
    debut       timestamp(6)  not null,
    fin         timestamp(6)  not null,
    lieu        varchar(255),
    description varchar(5000)
);
-- le planning cherche les événements d'une semaine : on range donc par date de début
create index ix_evenement_debut on evenement (debut);

-- Qui participe à quel événement
create table evenement_participant (
    evenement_id    bigint not null,
    participants_id bigint not null,
    constraint pk_evenement_participant primary key (evenement_id, participants_id),
    constraint fk_evenement_participant_evenement foreign key (evenement_id) references evenement (id),
    constraint fk_evenement_participant_membre foreign key (participants_id) references membre (id)
);
create index ix_evenement_participant_membre on evenement_participant (participants_id);

-- Le programme d'un événement : ses chants, dans l'ordre (position 0, 1, 2…)
create table evenement_chant (
    evenement_id bigint  not null,
    position     integer not null,
    chants_id    bigint  not null,
    constraint pk_evenement_chant primary key (evenement_id, position),
    constraint ck_evenement_chant_position check (position >= 0),
    constraint fk_evenement_chant_evenement foreign key (evenement_id) references evenement (id),
    constraint fk_evenement_chant_chant foreign key (chants_id) references chant (id)
);
create index ix_evenement_chant_chant on evenement_chant (chants_id);

-- Les invitations envoyées par les administrateurs
create table invitation (
    id        bigint generated by default as identity primary key,
    code      varchar(255) not null,
    expire_le timestamp(6) not null,
    utilisee  boolean      not null default false,
    constraint uk_invitation_code unique (code)
);
